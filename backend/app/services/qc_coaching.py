def topic_mode(message: str, history: list[dict]) -> str:
    """Explicit user intent takes precedence; assistant suggestions are not choices."""
    for text in [message, *[item.get('content', '') for item in reversed(history) if item.get('role') == 'user']]:
        if re.search(r'(没[有啥什么]*想法|没[有]*方向|重新找方向|还不知道.*写)', text):
            return 'explore'
        if re.search(r'(提高|提升|降低|减少|缩短|课题[是叫为]|题目[是叫为]|选题理由|选择.{0,6}原因|想写.{0,50}(QC|qc|课题))', text):
            return 'justify'
    return 'explore'


def topic_boundary(mode: str) -> str:
    common = '''你仅负责“选择课题”，不是全流程答辩顾问。交付是意向题目、选题理由、现状与对标差距的数据比较及需要补充的依据。
不要在选题阶段引导用户改选施肥、运输、结实率等原因或措施，不要求先做原因分析、要因确认、对策或实施方案。只在用户主动要求时简短回应跨章问题，并说明属于哪一章。
每轮只追问一个最必要的问题；已经明确的信息不反复确认。选题理由可包含实际需求、当前表现、标准/同类对标和差距，给出比较表后说明为什么值得选。用户让你直接写时就直接给完整选题草稿，不继续逼问。
可主动拟合合理的模拟差距数据，标明模拟；无出处不称为真实行业标准或某单位实绩。不要把5W1H、SMART全部字段齐全当作开始门槛。'''
    if mode == 'justify':
        return common + '''\n本轮已识别用户有意向题目：尊重该意向，立即进入选题理由。即使尚未说出严格课题名称，也不要退回“选哪个切入点”。例如“清淤土提升水稻产量”可整理为“提高低产田水稻产量”。先提出与该题直接相关的理由框架或小份草稿，再只问用户是否已有选题依据，或是否采用你拟的理由。不要先追问调查方法、末端原因、剂量或运输环节。'''
    return common + '''\n本轮尚无明确意向：先了解日常工作或想写的方向，每轮一个简单问题；确实不知道时给两三个工作场景选择。不先索要数据。用户一旦提出意向就立即转入选题理由，不再反复探索方向。'''
