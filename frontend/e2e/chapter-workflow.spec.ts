// Run with the isolated run_local_acceptance API and VITE_API_BASE_URL.
test('无Excel手动编写、审核、刷新恢复和固定版本导出', async ({page}) => {
  test.skip(!process.env.QC_LOCAL_ACCEPTANCE, '需要独立本地验收API')
  await page.goto('/authoring')
  await expect(page.getByRole('heading',{name:'逐章编写与审核'})).toBeVisible()
  await expect(page.getByRole('button',{name:'编写/打开'})).toHaveCount(11)
  await page.getByRole('button',{name:'编写/打开'}).first().click()
  await page.getByLabel('章节正文').fill('排涝站巡检记录完整性课题；当前证据待补，不声明已经实施。')
  await page.getByRole('button',{name:'保存草稿',exact:true}).click()
  await expect(page.getByText('内容：draft',{exact:true})).toBeVisible()
  await page.getByText('保留待核实',{exact:true}).click()
  await page.getByText('作者接受',{exact:true}).click()
  await expect(page.getByText('审核：approved',{exact:true})).toBeVisible()
  await expect(page.getByText('证据：missing',{exact:true})).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'编写/打开'}).first().click()
  await expect(page.getByLabel('章节正文')).toHaveValue(/排涝站巡检/)
  await page.screenshot({path:'../.venv/acceptance/authoring.png',fullPage:true})
  await page.goto('/ppt')
  await page.getByRole('button',{name:'导出前检查',exact:true}).click()
  await expect(page.getByText(/证据/).first()).toBeVisible()
  await page.getByRole('button',{name:/生成PPT/}).click()
  await expect(page.getByRole('button',{name:/下\s*载/}).first()).toBeVisible()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button',{name:/下\s*载/}).first().click()
  const file = await downloaded
  await file.saveAs('../.venv/acceptance/browser-report.pptx')
  await page.screenshot({path:'../.venv/acceptance/export.png',fullPage:true})
})

test('新资料上传、清洗确认与撤销保持版本可追溯', async ({ request }) => {
  test.skip(!process.env.QC_LOCAL_ACCEPTANCE, '需要独立本地验收API')
  const base = process.env.QC_LOCAL_ACCEPTANCE_BASE_URL || 'http://127.0.0.1:52889'
  const project = `e2e-material-${Date.now()}`
  const upload = await request.post(`${base}/api/projects/${project}/materials`, { multipart: { file: { name: '巡检.txt', mimeType: 'text/plain', buffer: Buffer.from('原始巡检记录', 'utf8') } } })
  expect(upload.status()).toBe(202)
  const item = await upload.json()
  const manifest = await (await request.get(`${base}/api/projects/${project}/materials/${item.material_id}/parse?version=${item.version}`)).json()
  const locator = `${manifest.units[0].locator}::${manifest.units[0].regions[0].region_id}`
  const previewResponse = await request.post(`${base}/api/projects/${project}/materials/${item.material_id}/cleaning-preview`, { data: { base_version: item.version, operations: [{ operation_id: 'e2e-op', category: 'document', target_locator: locator, before: '原始巡检记录', after: '已清洗巡检记录', reason: '人工确认', risk: 'low' }] } })
  expect(previewResponse.ok()).toBeTruthy()
  const preview = await previewResponse.json()
  const applied = await request.post(`${base}/api/projects/${project}/materials/${item.material_id}/cleaning-apply`, { data: { preview_id: preview.preview_id, diff_digest: preview.diff_digest, confirmed_operation_ids: ['e2e-op'] } })
  expect(applied.ok()).toBeTruthy()
  const receipt = await applied.json()
  expect(receipt.parent_version).toBe(item.version)
  const undone = await request.post(`${base}/api/projects/${project}/materials/${item.material_id}/cleaning-undo`, { data: { base_version: receipt.version, restore_version: item.version } })
  expect(undone.ok()).toBeTruthy()
  expect((await undone.json()).parent_version).toBe(receipt.version)
})

test('浏览器资料清洗必须先预览再确认，撤销保留原文',async({page})=>{
 test.skip(!process.env.QC_LOCAL_ACCEPTANCE,'需要独立本地验收API')
 await page.goto('/authoring')
 await expect(page.getByRole('heading',{name:'逐章编写与审核'})).toBeVisible()
 await page.locator('input[type="file"]').setInputFiles({name:'现场记录.txt',mimeType:'text/plain',buffer:Buffer.from('原始现场记录','utf8')})
 await page.getByRole('button',{name:'整理资料内容'}).click()
 await page.getByLabel('清洗后的内容').fill('整理后的现场记录')
 await page.getByRole('button',{name:'生成变更预览'}).click()
 await expect(page.getByRole('button',{name:'确认并应用'})).toBeDisabled()
 await page.getByRole('button',{name:/^确\s*认$/}).click()
 await page.getByRole('button',{name:'确认并应用'}).click()
 await expect(page.getByText('现场记录.txt · v2',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'撤销到上一版本'}).click()
 await expect(page.getByText('现场记录.txt · v3',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'整理资料内容'}).click()
 await expect(page.getByLabel('清洗后的内容')).toHaveValue('原始现场记录')
})
